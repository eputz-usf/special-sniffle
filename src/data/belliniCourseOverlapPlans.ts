const corePlans: BelliniCourseOverlapPlan[] = degrees
  .filter((degree) => coreDegreeSlugs.includes(degree.slug))
  .map((degree) => {
    const fourYearPlan = degree.officialLinks?.plans?.find((plan) =>
      plan.label.toLowerCase().includes('4 year'),
    );
    const courses = readyCourseListsBySlug[degree.slug] ?? [];

    return {
      slug: degree.slug,
      name: degree.name,
      focus: degree.bestFor,
      description: degree.description,
      planStatus: courses.length ? 'ready' : 'placeholder',
      sourceLabel: fourYearPlan?.label,
      sourceUrl: fourYearPlan?.url,
      courses,
    } satisfies BelliniCourseOverlapPlan;
  });

const interdisciplinaryPlans: BelliniCourseOverlapPlan[] = plannedHighSchoolFutureDegreeOptions.map(
  (degree) => {
    const fourYearPlan = degree.planningResources.find((resource) =>
      resource.label.toLowerCase().includes('4-year'),
    );
    const courses = readyCourseListsBySlug[degree.slug] ?? [];

    return {
      slug: degree.slug,
      name: degree.name,
      focus: degree.focus,
      description: degree.description,
      planStatus: courses.length ? 'ready' : 'placeholder',
      sourceLabel: fourYearPlan?.label,
      sourceUrl: fourYearPlan?.url,
      courses,
    } satisfies BelliniCourseOverlapPlan;
  },
);

export const belliniCourseOverlapPlans = [
  ...corePlans,
  ...interdisciplinaryPlans,
];

export function getBelliniCourseOverlapPlanBySlug(slug: string | undefined) {
  return belliniCourseOverlapPlans.find((plan) => plan.slug === slug);
}
